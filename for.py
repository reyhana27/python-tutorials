# A for loop repeats code for every item in a sequence

# range(5) produces the numbers 0, 1, 2, 3 and 4

for number in range(5):
    print(number)

# A for loop can also go through items in a list

fruits = ["apple", "banana", "orange"]

for fruit in fruits:
    print(fruit)

# range(1, 6) produces the numbers 1 through 5

for number in range(1, 6):
    print(number)

