# An if statement allows Python to make a decision

# The code inside the if statement runs when the condition is True

age = 18

if age >= 18:
    print("You are an adult")

# else runs when the if condition is False

temperature = 15

if temperature > 20:
    print("It is warm")
else:
    print("It is cold")

# elif checks another condition

score = 75

if score >= 80:
    print("Grade A")
elif score >= 60:
    print("Grade B")
else:
    print("Grade C")

