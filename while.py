# A while loop repeats code while a condition is True

number = 1

while number <= 5:
    print(number)
    number = number + 1

# The variable must change inside the loop
# otherwise the loop may continue forever

countdown = 3

while countdown > 0:
    print(countdown)
    countdown = countdown - 1

print("Finished")

