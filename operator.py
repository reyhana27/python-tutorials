# Operators in Python are used to perform calculations and comparisons

# + adds two values
# - subtracts one value from another
# * multiplies two values
# / divides one value by another

a = 10
b = 5

addition = a + b        # result is 15
subtraction = a - b     # result is 5
multiplication = a * b  # result is 50
division = a / b        # result is 2.0

print(addition)
print(subtraction)
print(multiplication)
print(division)

# == checks if two values are equal
print(a == b)           # result is False

